/**
 * Pre-computes a Natural Earth–projected world land path + marker coordinates for
 * src/data/worldMap.ts. Run once via: node scripts/gen-worldmap.mjs
 */
import fs from "node:fs";
import { geoNaturalEarth1, geoPath, geoCentroid } from "d3-geo";
import * as topojson from "topojson-client";

const W = 1000, H = 500;
const land = JSON.parse(fs.readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const countries = JSON.parse(fs.readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"));
const landFeature = topojson.feature(land, land.objects.land);
const projection = geoNaturalEarth1().fitExtent([[6, 6], [W - 6, H - 6]], landFeature);
const d = geoPath(projection)(landFeature);

const byName = {
  India: "origin",
  "United Arab Emirates": "UAE",
  "Saudi Arabia": "Saudi Arabia",
  Oman: "Oman",
  Qatar: "Qatar",
  Kuwait: "Kuwait",
  Bahrain: "Bahrain",
  Israel: "Israel",
  Mauritius: "Mauritius",
};
const markers = [];
for (const f of topojson.feature(countries, countries.objects.countries).features) {
  const name = f.properties?.name ?? f.properties?.NAME;
  if (name && byName[name]) {
    const c = geoCentroid(f);
    if (name === "Mauritius") {
      const p = projection([57.57, -20.25]);
      markers.push({ key: byName[name], name: "Mauritius", x: p[0], y: p[1] });
      continue;
    }
    const p = projection(c);
    markers.push({ key: byName[name], name, x: p[0], y: p[1] });
  }
}
for (const [label, lon, lat] of [["Mauritius", 57.57, -20.25], ["Bahrain", 50.55, 26.07]]) {
  if (!markers.some((m) => m.name === label)) {
    const p = projection([lon, lat]);
    markers.push({ key: label, name: label, x: p[0], y: p[1] });
  }
}
// Europe region marker (Frankfurt as representative of "European markets")
const eu = projection([8.68, 50.11]);
markers.push({ key: "Europe", name: "Europe (selected markets)", x: eu[0], y: eu[1] });

const out = `// GENERATED by scripts/gen-worldmap.mjs — Natural Earth 110m land (public domain) projected with geoNaturalEarth1.
export const WORLD_PATH = ${JSON.stringify(d)};
export const WORLD_VIEWBOX = "0 0 ${W} ${H}";
export interface MapMarker { key: string; name: string; x: number; y: number; }
export const MAP_MARKERS: MapMarker[] = ${JSON.stringify(markers, null, 2)};
`;
fs.writeFileSync("src/data/worldMap.ts", out);
console.log("wrote src/data/worldMap.ts", markers.map((m) => `${m.key}(${m.x.toFixed(0)},${m.y.toFixed(0)})`).join(" "));
